// Package scanner extracts convgen declarations from Go source comments.
package scanner

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

// GeneratedMarker identifies files emitted by convgen.
const GeneratedMarker = "// Code generated by convgen. DO NOT EDIT."

var (
	declStartRE    = regexp.MustCompile(`^[ \t]*//convgen:[ \t]*(.*)$`)
	continuationRE = regexp.MustCompile(`^[ \t]*//(?: {2,}|\t)(.*)$`)
)

// RawDecl is a single declaration recovered from source comments.
type RawDecl struct {
	File     string
	Line     int
	Content  string
	RawLines []string
	// LineStarts maps each RawLines entry to its byte offset in Content.
	LineStarts []int
}

// ScanFile scans one Go file. Generated convgen files are ignored.
func ScanFile(path string) ([]RawDecl, error) {
	decls, _, err := ScanFileInfo(path)
	return decls, err
}

// ScanFileInfo scans one Go file and reports whether it is generated by convgen.
func ScanFileInfo(path string) ([]RawDecl, bool, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, false, err
	}
	lines := strings.Split(string(data), "\n")
	generated := len(lines) > 0 && trimCR(lines[0]) == GeneratedMarker
	if generated {
		return nil, true, nil
	}

	var (
		decls   []RawDecl
		current *RawDecl
	)
	flush := func() {
		if current != nil {
			decls = append(decls, *current)
			current = nil
		}
	}

	for i, line := range lines {
		line = trimCR(line)
		if match := declStartRE.FindStringSubmatch(line); match != nil {
			flush()
			current = &RawDecl{
				File:       path,
				Line:       i + 1,
				Content:    match[1],
				RawLines:   []string{commentText(line)},
				LineStarts: []int{0},
			}
			continue
		}
		if current != nil {
			if match := continuationRE.FindStringSubmatch(line); match != nil {
				current.LineStarts = append(current.LineStarts, len(current.Content)+1)
				current.Content += " " + match[1]
				current.RawLines = append(current.RawLines, commentText(line))
				continue
			}
			flush()
		}
	}
	flush()
	return decls, false, nil
}

// ScanFiles scans files in deterministic path order.
func ScanFiles(paths []string) ([]RawDecl, error) {
	files := append([]string(nil), paths...)
	sort.Strings(files)
	var decls []RawDecl
	for _, path := range files {
		found, err := ScanFile(path)
		if err != nil {
			return nil, fmt.Errorf("扫描 %s 失败: %w", path, err)
		}
		decls = append(decls, found...)
	}
	return decls, nil
}

// IsGenerated reports whether data starts with convgen's generated marker.
func IsGenerated(data []byte) bool {
	line := string(data)
	if i := strings.IndexByte(line, '\n'); i >= 0 {
		line = line[:i]
	}
	return trimCR(line) == GeneratedMarker
}

func commentText(line string) string {
	i := strings.Index(line, "//")
	if i < 0 {
		return ""
	}
	return line[i+2:]
}

func trimCR(s string) string {
	return strings.TrimSuffix(s, "\r")
}
